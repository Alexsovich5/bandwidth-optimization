/*
 * Hand-built frames for the packet decoder tests. IPv4 header checksums are
 * left at zero: the decoder does not verify them.
 *
 * Addresses: 192.168.1.10 -> 10.0.0.20 unless noted.
 */

#define ETH_HDR(type_hi, type_lo) \
    0x00, 0x11, 0x22, 0x33, 0x44, 0x55, \
    0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, \
    type_hi, type_lo

/* Ethernet + IPv4 (IHL 5, TOS 0) + UDP 40000 -> 5060, 4 bytes of payload. */
static const unsigned char frame_eth_udp_sip[] = {
    ETH_HDR(0x08, 0x00),
    0x45, 0x00, 0x00, 0x20,       /* v4, IHL 5, TOS 0, total length 32 */
    0x12, 0x34, 0x00, 0x00,       /* id, no flags, offset 0 */
    0x40, 0x11, 0x00, 0x00,       /* TTL 64, proto UDP, checksum */
    0xc0, 0xa8, 0x01, 0x0a,       /* 192.168.1.10 */
    0x0a, 0x00, 0x00, 0x14,       /* 10.0.0.20 */
    0x9c, 0x40, 0x13, 0xc4,       /* sport 40000, dport 5060 */
    0x00, 0x0c, 0x00, 0x00,       /* UDP length 12, checksum */
    'S', 'I', 'P', '!'
};

